// ---------------------------------------------------------------- forms

// The three checklist answers that are also as-built facts about the opening.
const MAPS_TO: Record<string, string> = {
  measured_width: "job_openings.measured_width_in",
  measured_height: "job_openings.measured_height_in",
  centre_post: "job_openings.center_post_fitted",
};

function emitForm(key: string, name: string, audience: "client" | "crew", groups: FieldGroup[]) {
  say(`
  -- ${name}
  insert into form_templates (company_id, key, name, audience)
  values (v_company, ${q(key)}, ${q(name)}, ${q(audience)})
  on conflict (company_id, key) do update set name = excluded.name
  returning id into v_template;

  insert into form_versions (company_id, template_id, version, published_at)
  values (v_company, v_template, 1, now())
  on conflict (template_id, version) do update set published_at = coalesce(form_versions.published_at, now())
  returning id into v_version;`);

  groups.forEach((g, gi) => {
    const gkey = slug(g.title);
    say(`
  insert into form_groups (company_id, version_id, key, title, blurb, sort_order)
  values (v_company, v_version, ${q(gkey)}, ${q(g.title)}, ${q(g.blurb)}, ${gi})
  on conflict (version_id, key) do update set title = excluded.title, sort_order = excluded.sort_order
  returning id into v_group;`);

    g.fields.forEach((f, fi) => {
      say(`  insert into form_fields (company_id, version_id, group_id, key, label, type, options, required, help, maps_to, sort_order)
  values (v_company, v_version, v_group, ${q(f.id)}, ${q(f.label)}, ${q(f.type)}::field_type, ${arr(f.options ?? [])}, ${f.required ?? false}, ${q(f.help)}, ${q(MAPS_TO[f.id])}, ${gi * 100 + fi})
  on conflict (version_id, key) do update set
    label = excluded.label, type = excluded.type, options = excluded.options,
    required = excluded.required, help = excluded.help, group_id = excluded.group_id,
    sort_order = excluded.sort_order;`);
    });
  });
}

emitForm("onboarding", "Customer onboarding Q&A", "client", ONBOARDING);
emitForm("qa_checklist", "Installation QA checklist", "crew", QA_CHECKLIST);

