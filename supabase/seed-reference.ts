// Emits the reference SQL: the rows the app needs before anyone can use it.
//
//   node supabase/seed-reference.ts > /tmp/reference.sql
//
// Everything here is idempotent, and everything here is REAL. There is no
// invented operating data — no fake clients, no fake jobs, no fake crew. The
// forms are the questions HydroDam actually asks, generated from lib/forms.ts
// so the database and the UI can never disagree about a field key. The two
// users are the two people who exist. Crew get added from the Team screen.
//
// The automations are seeded DISARMED with no epoch. That is not caution for
// its own sake: `armed_requires_epoch` plus an epoch of "now" is the only thing
// standing between the first cron run and three thousand dormant leads.

import { ONBOARDING, QA_CHECKLIST, type FieldGroup } from "../lib/forms.ts";
import {
  ACKNOWLEDGMENT, AGREEMENT_VERSION, ESIGN_CONSENT, TERMS_OF_SALE, WARRANTY,
} from "../lib/agreement.ts";

const q = (s: string | null | undefined): string =>
  s == null ? "null" : `'${s.replace(/'/g, "''")}'`;

const arr = (items: string[]): string =>
  items.length === 0 ? "'{}'" : `array[${items.map(q).join(",")}]::text[]`;

const jsonb = (v: unknown): string => `${q(JSON.stringify(v))}::jsonb`;

const slug = (s: string): string =>
  s.toLowerCase().replace(/[^a-z0-9]+/g, "_").replace(/^_|_$/g, "");

const out: string[] = [];
const say = (s: string) => out.push(s);

say(`-- Generated by supabase/seed-reference.ts. Do not edit by hand.
begin;

do $seed$
declare
  v_company uuid;
  v_template uuid;
  v_version uuid;
  v_group uuid;
begin
  select id into v_company from companies where slug = 'hydrodam';
  if v_company is null then
    raise exception 'no hydrodam company row — run supabase/bootstrap.sql first';
  end if;
`);

